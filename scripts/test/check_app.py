# アプリ画面（/app/）をスマホの大きさで開いて、地図・釣り場の選択・下のシートを確かめる
import os
from playwright.sync_api import sync_playwright

BASE = os.environ.get("BASE", "https://tsuredoki-kansai.mametarou0510mame.workers.dev")
os.makedirs("shots", exist_ok=True)
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, is_mobile=True, has_touch=True,
                        geolocation={"latitude": 34.70, "longitude": 135.30}, permissions=["geolocation"], locale="ja-JP")
    pg = ctx.new_page()
    errs = []
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None)
    pg.goto(BASE + "/app/", timeout=60000)
    pg.wait_for_timeout(6000)
    pg.screenshot(path="shots/app1-map.png")
    r = pg.request.get(BASE + "/app-data/spot/minami-ashiyahama-minami-gogan.json")
    print(f"::notice::spot json {r.status} {len(r.body())} bytes {r.headers.get('content-type')}")
    pg.click("text=近くのポイント")
    pg.wait_for_timeout(3000)
    pg.screenshot(path="shots/app2-near.png")
    pg.locator(".fa-near button").first.click()
    pg.wait_for_timeout(5000)
    pg.screenshot(path="shots/app3-peek.png")
    pg.wait_for_timeout(2500)
    pg.screenshot(path="shots/app4-full.png")
    pg.locator(".fa-sheet").evaluate("e => e.scrollTo(0, e.scrollHeight * 0.55)")
    pg.wait_for_timeout(1500)
    pg.screenshot(path="shots/app5-methods.png")
    pg.locator(".fa-sheet").evaluate("e => e.scrollTo(0, e.scrollHeight)")
    pg.wait_for_timeout(1000)
    pg.screenshot(path="shots/app6-gear.png")
    pg.locator(".fa-sheet").evaluate("e => e.scrollTo(0, 400)")
    pg.wait_for_timeout(800)
    pg.screenshot(path="shots/app7-sticky-close.png")
    pg.click(".fa-back")
    pg.wait_for_timeout(2000)
    pg.screenshot(path="shots/app8-closed.png")
    print(f"::notice::閉じたあと sheet={pg.locator('.fa-sheet').get_attribute('class')} url={pg.url}")
    # 全国の潮位ポイント
    pg.evaluate("() => { document.querySelector('.fa-map') && window.scrollTo(0,0); }")
    pg.goto(BASE + "/app/?tide=HK", timeout=60000)
    pg.wait_for_timeout(8000)
    pg.screenshot(path="shots/app9-tide-top.png")
    pg.locator(".fa-sheet").evaluate("e => e.scrollTo(0, 700)")
    pg.wait_for_timeout(1500)
    pg.screenshot(path="shots/app10-tide-graph.png")
    pg.locator(".fa-sheet").evaluate("e => e.scrollTo(0, e.scrollHeight)")
    pg.wait_for_timeout(1500)
    pg.screenshot(path="shots/app11-tide-forecast.png")
    pg.click(".fa-back")
    pg.wait_for_timeout(1500)
    pg.evaluate("() => 0")
    pg.mouse.wheel(0, 0)
    pg.screenshot(path="shots/app12-after-tide.png")
    print(f"::notice::tide markers={pg.locator('path.leaflet-interactive').count()}")
    print(f"::notice::errors={errs[:5]}")
    b.close()

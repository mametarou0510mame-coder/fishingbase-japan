def P(x):
    return f"{x * 100:.0f}パーセント"


real = ml3.real_day
WINTER = ("12", "01", "02")


def month_rate(days, sp, m):
    ds = [v for k, v in days.items() if k[5:7] == m and real(v)]
    return sum(1 for v in ds if sp in v["s"]) / len(ds)


def winter(days):
    return {k: v for k, v in days.items() if k[5:7] in WINTER and real(v)}


def wrate(days, sp):
    w = winter(days)
    return sum(1 for v in w.values() if sp in v["s"]) / len(w)


def by_season(days, sp):
    """冬ごと（12月の年で数える）の割合"""
    g = {}
    for k, v in winter(days).items():
        y = int(k[:4]) if k[5:7] == "12" else int(k[:4]) - 1
        g.setdefault(y, []).append(sp in v["s"])
    return {y: sum(x) / len(x) for y, x in g.items() if len(x) >= 30}



def mrate(days, sp, months=None):
    """その魚が報告された日の割合（月ごと、または指定した月の合計）"""
    sps = [sp] if isinstance(sp, str) else sp
    act, hit = Counter(), Counter()
    for d, s in days.items():
        m = int(d[5:7])
        act[m] += 1
        hit[m] += any(x in s for x in sps)
    if months:
        a = sum(act[m] for m in months)
        return sum(hit[m] for m in months) / a if a else 0
    return [hit[m] / act[m] if act[m] else 0 for m in range(1, 13)]


def nxt(d, k=1):
    return (date.fromisoformat(d) + timedelta(days=k)).isoformat()


def persist(days, sp, k=1, months=None):
    """今日その魚が出た日／出なかった日の、k日後に出た割合"""
    a = b = c = e = 0
    for d, s in days.items():
        if months and int(d[5:7]) not in months:
            continue
        nd = nxt(d, k)
        if nd not in days:
            continue
        if sp in s:
            a += 1
            b += sp in days[nd]
        else:
            c += 1
            e += sp in days[nd]
    return (b / a if a else 0), (e / c if c else 0), a, c


def cond(days, A, B, months=None):
    """A が出た日／出なかった日に、B も出た割合"""
    a = b = c = e = 0
    for d, s in days.items():
        if months and int(d[5:7]) not in months:
            continue
        if A in s:
            a += 1
            b += B in s
        else:
            c += 1
            e += B in s
    return (b / a if a else 0), (e / c if c else 0), a, c


def md(s):
    return f"{int(s[5:7])}月{int(s[8:10])}日"



# ---------------- この魚が釣れた日、ほかに何が釣れた？ ----------------
def condn(days, src, A, B, months, lo, hi):
    a = b = c = e = 0
    for d, s in days.items():
        if int(d[5:7]) not in months or not (lo <= src[d].get("n", 0) < hi):
            continue
        if A in s:
            a += 1
            b += B in s
        else:
            c += 1
            e += B in s
    return (b / a if a else 0), (e / c if c else 0), a, c



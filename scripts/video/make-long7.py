def tilt(days, sp, keys):
    """その魚が報告された日と、同じ月の報告されなかった日で、時間の印の割合をくらべる。
    比べるのは、その魚が5日以上報告された月だけ（季節のちがいを消すため）。"""
    months = Counter(d[5:7] for d, v in days.items() if sp in v.get("s", {}))
    ms = {m for m, c in months.items() if c >= 5}
    a, b, nd = Counter(), Counter(), 0
    for d, v in days.items():
        if d[5:7] not in ms or not v.get("t"):
            continue
        if sp in v["s"]:
            a.update(v["t"])
            nd += 1
        else:
            b.update(v["t"])
    ta, tb = sum(a.values()), sum(b.values())
    return {"days": nd, "with": {k: a[k] / ta for k in keys}, "wo": {k: b[k] / tb for k in keys}, "ms": sorted(int(m) for m in ms)}



def split_line(ln, mx=66):
    """字幕が3行にならないよう、長い文は「。」で分ける"""
    if len(ln) <= mx:
        return [ln]
    parts = [x for x in re.split(r"(?<=。)", ln) if x]
    out, cur = [], ""
    for x in parts:
        if cur and len(cur) + len(x) > mx:
            out.append(cur)
            cur = x
        else:
            cur += x
    if cur:
        out.append(cur)
    return out



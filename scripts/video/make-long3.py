def sun_hours(d, lat=34.69, lon=135.19):
    n = d.timetuple().tm_yday
    decl = 23.44 * math.sin(math.radians(360 / 365 * (n - 81)))
    ha = math.degrees(math.acos(-math.tan(math.radians(lat)) * math.tan(math.radians(decl)) - 0.0145 / (math.cos(math.radians(lat)) * math.cos(math.radians(decl)))))
    b = math.radians(360 / 365 * (n - 81))
    eot = 9.87 * math.sin(2 * b) - 7.53 * math.cos(b) - 1.5 * math.sin(b)
    noon = 12 + (135 - lon) / 15 - eot / 60
    return noon - ha / 15, noon + ha / 15


def hm(h):
    m = int(round(h * 60))
    return f"{m // 60}:{m % 60:02d}"


def hm_say(h):
    m = int(round(h * 60))
    return f"{m // 60}時{m % 60}分"


def pct(v):
    return f"{v * 100:.0f}%"


def hist_days(slug):
    return json.load(open(f"data/history/{slug}.json", encoding="utf-8"))["days"]


def real_day(v):
    """「釣果なし」「◯時現在」だけの日は除く"""
    return any(not k.startswith(("本日", "悪天候")) and "現在" not in k and "釣果なし" not in k for k in v.get("s", {}))



def site_gear():
    """lib/gearShoreJigging.ts から製品を読む（サイトと動画で同じ名前・キーワードにする）"""
    ts = open("lib/gearShoreJigging.ts", encoding="utf-8").read()
    groups = {}
    for gid, body in re.findall(r'id: "(\w+)",.*?picks: \[(.*?)\n    \],', ts, re.S):
        groups[gid] = [dict(zip(("name", "spec", "why", "keyword"), m)) for m in
                       re.findall(r'\{ name: "(.*?)", spec: "(.*?)", why: "(.*?)", keyword: "(.*?)" \}', body)]
    return groups


